// Same answers, byte for byte; faster by batching inline Markdown, fast block
// lexing, a regex slug, and an output-array template renderer. Dependency-free.
//
// The semantics are makefun-site's own (see the kit's vendor README): front
// matter, template dialect, Markdown subset, slug rule and report. Where the
// README and the reference differ, this follows the reference code.

